#!/usr/bin/env python3
"""Draws the Herobrine trainer skin for the GoofBall pack from scratch.

Original work for this pack: every pixel is generated by this script (flat colours + a little
deterministic noise); no existing skin or texture was used as a base. Standard 64x64 skin layout
with 4px-wide arms (classic model).

    python3 -I scripts/make_herobrine_skin.py                     # writes pack/resourcepacks/Herobrine-Trainer-Skin.zip
    python3 -I scripts/make_herobrine_skin.py --preview out.png   # also writes an 8x front/back preview
"""
import random
import struct
import sys
import zlib
import zipfile
from pathlib import Path

W = H = 64
ROOT = Path(__file__).resolve().parent.parent
ZIP_PATH = ROOT / "pack" / "resourcepacks" / "Herobrine-Trainer-Skin.zip"
TEXTURE = "assets/rctmod/textures/trainers/single/herobrine.png"
MCMETA = '{\n  "pack": {\n    "pack_format": 34,\n    "description": "Herobrine skin for the GoofBall RCT trainer"\n  }\n}\n'

SKIN = (196, 164, 138)
SKIN_DARK = (150, 118, 96)
HAIR = (30, 26, 34)
EYE = (255, 255, 255)
MOUTH = (112, 78, 72)
SHIRT = (28, 88, 100)
SHIRT_LIGHT = (44, 120, 130)
SHIRT_DARK = (18, 62, 72)
PANTS = (48, 50, 74)
SHOE = (24, 24, 30)
EMBLEM = (170, 30, 40)

BOXES = {
    "head": (0, 0, 8, 8, 8),
    "body": (16, 16, 8, 12, 4),
    "rarm": (40, 16, 4, 12, 4),
    "larm": (32, 48, 4, 12, 4),
    "rleg": (0, 16, 4, 12, 4),
    "lleg": (16, 48, 4, 12, 4),
}

img = [[(0, 0, 0, 0)] * W for _ in range(H)]


def put(x, y, c):
    img[y][x] = (c[0], c[1], c[2], 255)


def faces(u, v, w, h, d):
    """Face rectangles (x, y, width, height) of a skin-layout box, keyed by face name."""
    return {
        "top": (u + d, v, w, d),
        "bottom": (u + d + w, v, w, d),
        "right": (u, v + d, d, h),
        "front": (u + d, v + d, w, h),
        "left": (u + d + w, v + d, d, h),
        "back": (u + 2 * d + w, v + d, w, h),
    }


def paint(box, fn):
    for name, (x0, y0, fw, fh) in faces(*box).items():
        for y in range(fh):
            for x in range(fw):
                put(x0 + x, y0 + y, fn(name, x, y))


def head(face, x, y):
    if face == "top":
        return HAIR
    if face == "bottom":
        return SKIN_DARK
    if face == "front":
        if y < 2 or (y < 3 and (x < 1 or x > 6)):
            return HAIR
        if y == 4 and x in (1, 2, 5, 6):
            return EYE
        if y == 6 and x in (3, 4):
            return MOUTH
        return SKIN
    if face == "back":
        return HAIR if y < 6 else SKIN
    if face == "right":  # the front of the face is on the right-hand side of this view
        return HAIR if y < 3 or (x <= 2 and y < 6) else SKIN
    return HAIR if y < 3 or (x >= 5 and y < 6) else SKIN  # left


def body(face, x, y):
    if face == "top":
        return SHIRT_LIGHT
    if face == "bottom":
        return PANTS
    if face == "front":
        if y == 0 and 2 <= x <= 5:
            return SKIN_DARK
        if y == 8 and 1 <= x <= 6:
            return SHIRT_DARK
        return SHIRT_LIGHT if x in (3, 4) and y > 0 else SHIRT
    if face == "back":
        if x in (3, 4) and y in (4, 5):
            return EMBLEM
        return SHIRT
    return SHIRT


def arm(face, x, y):
    if face == "bottom":
        return SKIN
    if face == "top":
        return SHIRT
    return SHIRT if y < 9 else SKIN


def leg(face, x, y):
    if face == "bottom":
        return SHOE
    if face == "top":
        return PANTS
    return PANTS if y < 9 else SHOE


paint(BOXES["head"], head)
paint(BOXES["body"], body)
paint(BOXES["rarm"], arm)
paint(BOXES["larm"], arm)
paint(BOXES["rleg"], leg)
paint(BOXES["lleg"], leg)

rng = random.Random(1307)
for y in range(H):
    for x in range(W):
        r, g, b, a = img[y][x]
        if a:
            n = rng.randint(-5, 5)
            img[y][x] = (max(0, min(255, r + n)), max(0, min(255, g + n)), max(0, min(255, b + n)), 255)


def png(pixels, width, height):
    raw = b"".join(b"\x00" + b"".join(bytes(p) for p in row) for row in pixels)

    def chunk(tag, data):
        c = struct.pack(">I", len(data)) + tag + data
        return c + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)

    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 6, 0, 0, 0))
            + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b""))


def preview(path, scale=8):
    """Front and back view side by side."""
    pw, ph = 36, 34
    canvas = [[(60, 64, 72, 255)] * pw for _ in range(ph)]
    f = {n: faces(*b) for n, b in BOXES.items()}

    def blit(rect, dx, dy):
        x0, y0, fw, fh = rect
        for y in range(fh):
            for x in range(fw):
                p = img[y0 + y][x0 + x]
                if p[3]:
                    canvas[dy + y][dx + x] = p

    def figure(ox, side):
        # seen from the front the character's right arm/leg are on the viewer's left
        a, b = ("rarm", "larm") if side == "front" else ("larm", "rarm")
        c, d = ("rleg", "lleg") if side == "front" else ("lleg", "rleg")
        blit(f["head"][side], ox + 4, 1)
        blit(f["body"][side], ox + 4, 9)
        blit(f[a][side], ox, 9)
        blit(f[b][side], ox + 12, 9)
        blit(f[c][side], ox + 4, 21)
        blit(f[d][side], ox + 8, 21)

    figure(1, "front")
    figure(19, "back")
    big = []
    for row in canvas:
        wide = [p for p in row for _ in range(scale)]
        big.extend([wide] * scale)
    Path(path).write_bytes(png(big, pw * scale, ph * scale))


if __name__ == "__main__":
    data = png(img, W, H)
    ZIP_PATH.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(ZIP_PATH, "w", zipfile.ZIP_DEFLATED) as z:
        for name, content in (("pack.mcmeta", MCMETA.encode()), (TEXTURE, data)):
            info = zipfile.ZipInfo(name, date_time=(2026, 11, 6, 0, 0, 0))  # fixed date: reproducible zip
            info.compress_type = zipfile.ZIP_DEFLATED
            z.writestr(info, content)
    print(f"wrote {ZIP_PATH} ({len(data)} byte texture)")
    if "--preview" in sys.argv:
        out = sys.argv[sys.argv.index("--preview") + 1]
        preview(out)
        print(f"preview: {out}")
